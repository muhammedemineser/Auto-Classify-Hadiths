# TIPP: Du kannst die Liste auch automatisch generieren lassen, wenn du viele hast.

RESTART_DRIVER_EVERY = 50  # Bei Einzelenseiten seltener neu starten nötig


def create_driver():
    options = Options()
    options.add_argument("--start-maximized")
    options.add_argument("--headless=new")
    options.add_argument("--disable-gpu")
    return webdriver.Chrome(options=options)


driver = create_driver()
count_processed = 0

try:
    for nr in missing_hadiths:
        # Wir nutzen die Struktur: part ist bei Sahihah oft irrelevant, wenn page direkt angesteuert wird.
        # Falls die Seite einen Part braucht, muss man diesen ggf. mitsenden.
        # Hier nutzen wir die direkte Page-Ansteuerung:
        url = f"https://ketabonline.com/ar/books/{book_id}/read?page={nr}"

        print(f"🔍 Hole fehlenden Hadith Nr./Seite: {nr}...", end="\r")
        driver.get(url)
        wait = WebDriverWait(driver, 15)

        try:
            # Warten bis der Text-Container da ist
            container = wait.until(
                EC.presence_of_element_located((By.CSS_SELECTOR, "div.book-page"))
            )
            time.sleep(1)  # Kurzer Moment für finales Rendering

            raw_text = container.text
            if raw_text:
                clean_line = " ".join(raw_text.split()).strip()

                # In separate Datei speichern, um Original nicht zu korrumpieren
                with open(f"{book_name}.txt", "a", encoding="utf-8") as f:
                    f.write(f"{clean_line}\n")
                    f.flush()

                count_processed += 1

        except Exception as e:
            print(f"\n⚠️ Fehler bei Hadith {nr}: {e}")

        # RAM-Management
        if count_processed % RESTART_DRIVER_EVERY == 0:
            driver.quit()
            driver = create_driver()

    print(
        f"\n\n✅ Fertig! {count_processed} fehlende Hadithe wurden in '{book_name}.txt' gespeichert."
    )

except KeyboardInterrupt:
    print("\n🛑 Abbruch durch Nutzer.")
finally:
    driver.quit()
