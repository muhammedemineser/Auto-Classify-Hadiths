# Regex: Einschub-Block (kann beliebig oft zwischen Isnād-Segmenten auftauchen)
RX_INTERJECTION = regex.compile(
    r"""
    (?xiu)
    (?:
      (?:%s)
      (?:\s++[\p{Arabic}]+){0,12}     # kurzer Tail: "أثنى عليه ابن معين ..." etc.
      \s*+[،:؛.\)\]]*
    )+
    """
    % ("|".join(sorted(map(regex.escape, INTERJECTION_PHRASES), key=len, reverse=True)))
)

# Regex: grobes Isnād-Segment (verb + name + optional interjections + linker ...)
RX_ISNAD = regex.compile(
    r"""
    (?xiu)
    (?:
      (?:%s)
      \s++
      [\p{Arabic}]+(?:\s+[\p{Arabic}]+){0,8}        # Name/kunya/nisba (grober Span)
      (?:\s*+[،:؛.]*)?
      (?:\s*+(?:(?:%s))\s*+)?                       # optionale Interjection
      (?:\s++(?:%s)\s++)?                           # optionaler linker (عن/أن/قال/و...)
    )+
    """
    % (
        "|".join(map(regex.escape, ISNAD_VERBS)),
        RX_INTERJECTION.pattern,
        "|".join(map(regex.escape, ISNAD_LINKERS)),
    )
)


