def strip_html(text: str) -> str:
    return re.sub(r"<[^>]+>", " ", text)


def normalize(text: str) -> str:
    text = ARABIC_DIACRITICS_RE.sub("", text)
    text = text.replace(TATWEEL, "")
    text = re.sub(r"[أإآ]", "ا", text)
    text = re.sub(r"ى", "ي", text)
    text = re.sub(r"ة", "ه", text)
    text = text.replace("\u200f", "").replace("\u200e", "")
    text = WAW_GAP_RE.sub(r"\1و", text)
    return text


def tokenize(text: str) -> List[str]:
    norm = normalize(strip_html(text))
    return [tok.strip().lower() for tok in TOKEN_RE.findall(norm) if tok.strip()]


STOPWORD_LOOKUP: DefaultDict[str, List[Tuple[str, ...]]] = defaultdict(list)
for phrase in HADITH_META_STOPWORDS:
    seq = tuple(tokenize(phrase))
    if not seq:
        continue
    STOPWORD_LOOKUP[seq[0]].append(seq)

PREFIX_LOOKUP: DefaultDict[str, List[Tuple[str, ...]]] = defaultdict(list)
for phrase in MATN_PREFIXES:
    seq = tuple(tokenize(phrase))
    if not seq:
        continue
    PREFIX_LOOKUP[seq[0]].append(seq)


def is_meta_token(token: str) -> bool:
    return not ARABIC_WORD_RE.match(token)


def extract_matn_tokens(
    tokens: Sequence[str], allow_span_detection: bool = True
) -> List[str]:
    tokens_list = list(tokens)
    if not tokens_list:
        return []

    def clean_window(window: Sequence[str]) -> List[str]:
        cleaned: List[str] = []
        j = 0
        while j < len(window):
            tok = window[j]
            skipped_len = 0
            for seq in STOPWORD_LOOKUP.get(tok, []):
                if list(window[j : j + len(seq)]) == list(seq):
                    skipped_len = len(seq)
                    break
            if skipped_len:
                j += skipped_len
                continue

            if tok in PUNCT_SKIP or tok in {'"', "'", "«", "»", "(", ")", "[", "]"}:
                j += 1
                continue

            if is_meta_token(tok) or tok in HADITH_META_STOPWORDS:
                break

            cleaned.append(tok)
            j += 1

        return cleaned

    def find_first_span() -> Tuple[int, int] | None:
        span_pairs = {'"': '"', "«": "»", "(": ")"}
        for idx, tok in enumerate(tokens_list):
            if tok not in span_pairs:
                continue
            close_tok = span_pairs[tok]
            try:
                end_idx = tokens_list.index(close_tok, idx + 1)
            except ValueError:
                continue
            if end_idx > idx + 1:
                return idx, end_idx
        return None

    def first_prefix_index() -> int | None:
        i = 0
        while i < len(tokens_list):
            tok = tokens_list[i]
            for seq in PREFIX_LOOKUP.get(tok, []):
                if tokens_list[i : i + len(seq)] == list(seq):
                    return i
            if tok == "و" and i + 1 < len(tokens_list):
                next_tok = tokens_list[i + 1]
                for seq in PREFIX_LOOKUP.get(next_tok, []):
                    if tokens_list[i + 1 : i + 1 + len(seq)] == list(seq):
                        return i
            i += 1
        return None

    span_tokens: List[str] = []
    span_start: int | None = None
    if allow_span_detection:
        span = find_first_span()
        if span:
            span_start, span_end = span
            span_tokens = clean_window(tokens_list[span_start + 1 : span_end])

    collected: List[str] = []

    if PREFIX_LOOKUP:
        i = 0
        active = False

        while i < len(tokens_list):
            token = tokens_list[i]
            matched_prefix = False

            for seq in PREFIX_LOOKUP.get(token, []):
                if list(tokens_list[i : i + len(seq)]) == list(seq):
                    active = True
                    matched_prefix = True
                    i += len(seq)
                    break

            if not matched_prefix and token == "و" and i + 1 < len(tokens_list):
                next_tok = tokens_list[i + 1]
                for seq in PREFIX_LOOKUP.get(next_tok, []):
                    if list(tokens_list[i + 1 : i + 1 + len(seq)]) == list(seq):
                        active = True
                        matched_prefix = True
                        i += 1 + len(seq)
                        break

            if matched_prefix:
                continue

            if active:
                skipped_len = 0
                for seq in STOPWORD_LOOKUP.get(token, []):
                    if list(tokens_list[i : i + len(seq)]) == list(seq):
                        skipped_len = len(seq)
                        break
                if skipped_len:
                    i += skipped_len
                    continue

                if token in PUNCT_SKIP or token in {'"', "'", "«", "»"}:
                    i += 1
                    continue

                if is_meta_token(token) or token in HADITH_META_STOPWORDS:
                    active = False
                else:
                    collected.append(token)

            i += 1
    else:
        collected = tokens_list

    prefix_start = first_prefix_index()
    if span_tokens:
        if not collected:
            return span_tokens
        if prefix_start is None or (
            span_start is not None and span_start < prefix_start
        ):
            return span_tokens

    return collected


def matn_tokens_for_matching(
    tokens: Sequence[str], require_prefix: bool, skip_span_detection: bool
) -> List[str]:
    if require_prefix:
        return extract_matn_tokens(tokens, allow_span_detection=not skip_span_detection)
    return list(tokens)
