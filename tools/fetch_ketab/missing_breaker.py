import re


def repair_hadith_logic(input_file, output_file):
    with open(input_file, "r", encoding="utf-8") as f:
        # Wir lesen die Zeilen und entfernen nur das \n am Ende
        lines = [line.rstrip("\n") for line in f]

    fixed_lines = []
    # Wir nehmen die erste Nummer im Dokument als Startpunkt
    expected_nr = None
    i = 0

    print(f"🚀 Starte Analyse von {len(lines)} Zeilen...")

    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue

        # WICHTIG: Wir suchen die Zahl irgendwo in der Zeile,
        # aber sie muss das Format "Zahl-" haben.
        # \b stellt sicher, dass wir nicht die 3430 in 13430 finden.
        match = re.search(r"\b(\d+)\s*-", line)

        if match:
            current_nr = int(match.group(1))

            if expected_nr is None:
                expected_nr = current_nr

            # Wenn die gefundene Nummer unsere erwartete Sequenznummer ist
            if current_nr == expected_nr:
                start_pos = match.start()
                pre_text = line[:start_pos].strip()
                post_text = line[start_pos:].strip()

                # Falls vor der Nummer noch Text war (wie die Überschrift)
                if pre_text:
                    if fixed_lines:
                        # Überschrift an den vorherigen Hadith-Block hängen
                        fixed_lines[-1] += " " + pre_text
                    else:
                        fixed_lines.append(pre_text)

                # Jetzt den eigentlichen Hadith hinzufügen
                fixed_lines.append(post_text)

                expected_nr += 1
                i += 1
                continue

            # Falls die Nummer nicht die erwartete ist (Lücke)
            else:
                # Wir prüfen, ob die erwartete Nummer vielleicht versteckt ist
                search_pattern = rf"\b({expected_nr})\s*-"

                found_hidden = False
                # Wir schauen in dieser und der nächsten Zeile
                for offset in [0, 1]:
                    if i + offset < len(lines):
                        target = lines[i + offset]
                        m_hidden = re.search(search_pattern, target)
                        if m_hidden:
                            # Gefunden! Wir behandeln diese Zeile nun im nächsten Durchlauf
                            # Indem wir i nicht erhöhen, aber die Zeile "vorbereiten"
                            if offset == 1:
                                # Aktuelle Zeile i zum vorherigen Block schlagen
                                fixed_lines[-1] += " " + lines[i]
                                i += 1
                            # Die Zeile mit der versteckten Nummer wird nun zur aktuellen Zeile i
                            found_hidden = True
                            break

                if found_hidden:
                    continue  # Springe zum Anfang der While-Schleife, i zeigt nun auf die Fundstelle
                else:
                    # Nicht gefunden, wir akzeptieren den Sprung in der Nummerierung
                    fixed_lines.append(line)
                    expected_nr = current_nr + 1
                    i += 1
        else:
            # Kein Treffer in dieser Zeile -> Text gehört zum vorherigen Hadith
            if fixed_lines:
                fixed_lines[-1] += " " + line
            else:
                fixed_lines.append(line)
            i += 1

    # Speichern und Säubern
    print(f"💾 Speichere sauberes Ergebnis...")
    with open(output_file, "w", encoding="utf-8") as f:
        for fl in fixed_lines:
            # Mehrfache Leerzeichen durch eines ersetzen
            clean_line = " ".join(fl.split())
            f.write(clean_line + "\n")

    print(f"✅ Reparatur abgeschlossen!")


